"""PORTAUDIO ITSELF, TORN DOWN AND BUILT BACK UP FOR EVERYBODY AT ONCE.

_terminate() IS PROCESS WIDE, NOT PER STREAM: IT INVALIDATES EVERY STREAM POINTER IN THE
PROCESS, NOT ONLY THE ONE THAT WENT WRONG. THE MICROPHONE AND THE SPEAKER USED TO EACH CALL
IT AFTER SHUTTING THEIR OWN STREAM, WHICH LEFT THE OTHER SIDE HOLDING A DEAD POINTER AND
FAILING -9986 ON ITS NEXT USE. ON AIRPODS THAT IS NOT RARE BUT ROUTINE, BECAUSE INPUT AND
OUTPUT ARE ONE DEVICE: OPENING THE MICROPHONE PUTS THE HEADSET INTO ITS TWO WAY PROFILE AND
RESETS THE OUTPUT UNDER THE HELD STREAM, SO THE SPEAKER REACHES FOR THE CURE WITH THE
MICROPHONE WIDE OPEN.

SO THE CURE BELONGS TO NEITHER OF THEM. EVERY HOLDER HANDS ITS STREAM OVER HERE, AND A RESET
SHUTS THE LOT BEFORE THE TEARDOWN AND LETS EACH BUILD ITS OWN AGAIN AFTER."""

import contextlib
import os
import threading

import sounddevice as sd

# EVERY LIVE STREAM'S OWNER, AS THE CALLBACK THAT LETS GO OF IT.
holders = []

# ONE RESET AT A TIME, AND NOBODY OPENING A STREAM DURING ONE. RE-ENTRANT BECAUSE THE
# LETTING GO HAPPENS INSIDE THE RESET THAT ASKED FOR IT.
lock = threading.RLock()

# THE SWAPPED DESCRIPTOR IS THE WHOLE PROCESS'S, SO ONLY ONE THREAD MAY HOLD IT SWAPPED.
# SPEAKING RUNS ON ITS OWN WORKERS WHILE THE KEY OPENS THE MICROPHONE, AND TWO THREADS
# SWAPPING AT ONCE CLOSED EACH OTHER'S SAVED COPY AND RAISED BAD FILE DESCRIPTOR.
# RE-ENTRANT BECAUSE A RESET GUARDS ITSELF AND CALLS HOLDERS THAT GUARD THEMSELVES.
hush = threading.RLock()

# HOW DEEP THE NESTING GOES, SO ONLY THE OUTERMOST ONE PUTS THE DESCRIPTOR BACK, AND THE
# REAL STDERR IT IS PUT BACK FROM.
depth = 0
kept = None


def surrender(release):
    """A STREAM HOLDER, ADDED TO WHAT A RESET WILL SHUT FIRST.

    THE CALLBACK TAKES NO ARGUMENTS AND MUST LEAVE ITS OWNER READY TO BUILD A FRESH STREAM
    ON NEXT USE, BECAUSE THAT IS EXACTLY WHAT IT WILL HAVE TO DO."""
    with lock:
        if release not in holders:
            holders.append(release)

    return release


def reset():
    """PORTAUDIO BUILT BACK FROM NOTHING, WITH EVERY STREAM IN THE PROCESS LET GO FIRST.

    THE ONLY CURE WHEN PORTAUDIO'S DEVICE LIST HAS GONE STALE AGAINST COREAUDIO, AND THE
    LAST ONE TRIED ANYWHERE, BECAUSE IT COSTS EVERY OPEN DEVICE ITS STREAM."""
    with lock:
        for release in list(holders):
            try:
                release()
            except Exception:
                pass  # A STREAM TOO FAR GONE TO SHUT IS ONE THE TEARDOWN TAKES ANYWAY.

        with quiet():
            sd._terminate()
            sd._initialize()


@contextlib.contextmanager
def quiet():
    """COREAUDIO'S OWN GRUMBLING, KEPT OFF THE LOG.

    PORTAUDIO PRINTS ||PaMacCore|| STRAIGHT DOWN FILE DESCRIPTOR 2 FROM C, WHERE PYTHON
    CANNOT REACH IT, AND A HEADSET WAKING UP EARNS ONE LINE PER ATTEMPT. THE DESCRIPTOR
    ITSELF IS SWAPPED FOR THE LENGTH OF THE CALL AND PUT BACK AFTER."""
    global depth, kept

    # THE LOCK IS HELD FOR THE SWAP ONLY, NEVER ACROSS THE WORK. A MICROPHONE NUDGING A
    # HEADSET FOR TWELVE SECONDS WOULD OTHERWISE HOLD EVERY SPOKEN BLOCK BEHIND IT.
    with hush:
        if depth == 0:
            kept = os.dup(2)

            with open(os.devnull, "w") as sink:
                os.dup2(sink.fileno(), 2)

        depth += 1

    try:
        yield
    finally:
        with hush:
            depth -= 1

            if depth == 0:
                os.dup2(kept, 2)
                os.close(kept)
                kept = None
