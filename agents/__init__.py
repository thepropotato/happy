"""
EVERYTHING HAPPY CAN DO. ONE MODULE PER PART OF THE MACHINE.

A MODULE HERE IS A NAMESPACE, NOT A MIND OF ITS OWN. IT EXPORTS TOOLS AND THE
ONE GRAPH IN brain.py CALLS THEM DIRECTLY. NOTHING HERE RUNS ITS OWN MODEL LOOP,
BECAUSE EVERY EXTRA HOP THROUGH THE MODEL IS ANOTHER SECOND OF SILENCE BEFORE
HAPPY SPEAKS, AND SILENCE IS THE ONE THING A VOICE ASSISTANT CANNOT AFFORD.

A MODULE THAT LATER NEEDS ITS OWN LOOP, AS THE BROWSER WILL, BECOMES A SUBGRAPH
AND STILL EXPORTS ONE TOOL FROM HERE. THE SHAPE OUT HERE DOES NOT CHANGE.

TO ADD A CAPABILITY: WRITE THE MODULE, GIVE IT A TOOLS LIST, ADD IT TO MODULES.
"""

from agents import bash, browser, desktop, files, system, vision

# ORDER IS THE ORDER THE MODEL SEES THEM IN. THE NARROW, SAFE ONES GO FIRST SO
# THEY READ AS THE OBVIOUS CHOICE BEFORE THE SHELL DOES. SEEING COMES BEFORE
# TOUCHING FOR THE SAME REASON: THE SCREEN SHOULD BE READ BEFORE IT IS CLICKED.
MODULES = [system, files, vision, desktop, browser, bash]


def tools():
    """EVERY TOOL FROM EVERY MODULE, FLAT, READY TO BIND TO A MODEL."""
    found = []

    for module in MODULES:
        found.extend(module.TOOLS)

    return found


def names():
    return [each.name for each in tools()]
