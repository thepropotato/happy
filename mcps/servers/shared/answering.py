"""WHAT EVERY TOOL ON EVERY SERVER ANSWERS WITH: ONE SHORT JSON STRING.

NOTHING HERE CATCHES ANYTHING. A TOOL THAT RAISES COMES BACK TO THE MODEL AS A
FAILED CALL CARRYING THE REASON, AND mcps/speaking.py ALREADY TURNS THAT INTO
ONE PLAIN LINE, SO CATCHING IT IN THE SERVER WOULD ONLY BURY THE REASON.
"""

import json

# ENOUGH FOR AN ANSWER TO BE USEFUL. THE CLIENT CUTS IT DOWN AGAIN BEFORE ANY OF
# IT IS SAID OUT LOUD, SO THIS ONLY GUARDS THE MODEL'S CONTEXT.
MOST = 4000


def ok(data):
    return json.dumps(data, default=str, ensure_ascii=False)[:MOST]


def some(text, most=300):
    """A FIELD SOMEBODY ELSE WROTE, WITH ITS NEWLINES AND ITS ESSAY TAKEN OFF."""
    return "" if not text else " ".join(str(text).split())[:most]
